/* ============ ENGINE ============ */
let LANG = "en";
function t(key, vars) {
  let s = (I18N[LANG] && I18N[LANG][key]) ?? I18N.en[key] ?? key;
  if (vars && typeof s === "string") for (const k in vars) s = s.replace(`{${k}}`, vars[k]);
  return s;
}
function detectLang() {
  try { const s = localStorage.getItem("lang"); if (s && I18N[s]) return s; } catch (e) {}
  const nav = (navigator.languages || [navigator.language || "en"]).map(l => l.slice(0, 2).toLowerCase());
  return nav.find(l => I18N[l]) || "en";
}
function applyStatic() {
  document.documentElement.lang = LANG;
  document.title = t("title");
  document.querySelectorAll("[data-i18n]").forEach(el => el.textContent = t(el.dataset.i18n));
  document.querySelectorAll("[data-i18n-html]").forEach(el => el.innerHTML = t(el.dataset.i18nHtml));
  document.querySelectorAll("[data-i18n-ph]").forEach(el => el.placeholder = t(el.dataset.i18nPh));
  document.querySelectorAll("[data-i18n-aria]").forEach(el => { const v = t(el.dataset.i18nAria); el.setAttribute("aria-label", v); el.title = v; });
}
function setLang(code, save = true) {
  if (!I18N[code]) return;
  LANG = code;
  if (save) { try { localStorage.setItem("lang", code); } catch (e) {} }
  applyStatic();
  if (typeof onLangChange === "function") onLangChange();
}
LANG = detectLang();
